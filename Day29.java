public class Day29 {
    public static void main(String[] args) {

        int k = 90;
        int l = 77;

        // Operator Kurang Dari (<)
        boolean KurangDari = k < l;
        System.out.println("Apakah " + k + " < " + l + "? " +KurangDari); 

        // Operator Lebih Dari (>)
        boolean LebihDari = k > l;
        System.out.println("Apakah " + k + " > " + l + "? " + LebihDari);

       
    }
}
