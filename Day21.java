public class Day21 {
    public static void main(String[] args) {

        String Angka = "80";
        int angka = Integer.parseInt(Angka);
        String Nilai = "44.99";
        double nilai = Double.parseDouble(Nilai);

        System.out.println("String menjadi int : " + angka);
        System.out.println("String menjadi double : " + nilai);
    }
}
