public class Day19 {
    public static void main(String[] args) {

        double angkaDouble = 48.90;
        int angkaInt = (int) angkaDouble; 

        long angkaLong = 156L;
        short angkaShort = (short) angkaLong; 

        System.out.println("Nilai awal angka double : " + angkaDouble);
        System.out.println("Hasil ke int : " + angkaInt);
        System.out.println("Nilai awal angka long : " + angkaLong);
        System.out.println("Hasil ke short : " + angkaShort);
    }
}
