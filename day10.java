public class Day10 {
    public static void main(String[] args) {
        short batasCommit = 100;
        long batasPenduduk = 100000;

        System.out.println("Batas Commit : " + batasCommit);
        System.out.println("Batas Penduduk : " + batasPenduduk);

        System.out.println("Nilai minimal short : " + Short.MIN_VALUE);
        System.out.println("Nilai maksimal short : " + Short.MAX_VALUE);

        System.out.println("Nilai minimal long : " + Long.MIN_VALUE);
        System.out.println("Nilai maksimal long : " + Long.MAX_VALUE);

        /*MIN_VALUE digunakan untuk melihat batas nilai minimal, 
        sedangkan MAX_VALUE digunakan untuk melihat batas nilai maksimal dari suatu tipe data.*/
    }
}
